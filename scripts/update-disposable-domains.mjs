// Refreshes convex/lib/disposableDomains.ts from the community list of throwaway email
// domains (https://github.com/disposable-email-domains/disposable-email-domains, CC0).
// Run with `node scripts/update-disposable-domains.mjs`, then commit the result.
import { writeFile } from "node:fs/promises";

const SOURCE =
  "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";

const response = await fetch(SOURCE);
if (!response.ok) throw new Error(`The list answered ${response.status}`);
const domains = (await response.text())
  .split("\n")
  .map((line) => line.trim().toLowerCase())
  .filter((line) => line && !line.startsWith("#"));

const file = `// Generated by scripts/update-disposable-domains.mjs from
// ${SOURCE}
// (CC0). Do not edit by hand.
export const DISPOSABLE_DOMAINS = ${JSON.stringify(domains.join("\n"))};
`;
await writeFile(new URL("../convex/lib/disposableDomains.ts", import.meta.url), file);
console.log(`${domains.length} domains written.`);
