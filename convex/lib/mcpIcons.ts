export type IconName = keyof typeof SHAPES;

const svg = (shapes: string, colour: string) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="${colour}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`;

const dataLink = (text: string) => `data:image/svg+xml;base64,${btoa(text)}`;

/** An icon in the chat's own grey, drawn darker on light chats and lighter on dark ones. */
export function icon(name: IconName): McpIcon[] {
  return [
    {
      src: dataLink(svg(SHAPES[name], "#3d3d3a")),
      mimeType: "image/svg+xml",
      sizes: ["any"],
      theme: "light",
    },
    {
      src: dataLink(svg(SHAPES[name], "#e8e6dc")),
      mimeType: "image/svg+xml",
      sizes: ["any"],
      theme: "dark",
    },
  ];
}
